export const CAPACITY = 3;

export function topicList(course) {
  return (TOPICS[course] ?? []).flatMap((g) =>
    g.items.map(([id, title, gear, param]) => ({ id, title, gear, group: g.group, param })));
}

export function findTopic(course, id) {
  return topicList(course).find((t) => t.id === id) ?? null;
}

export function paramFor(topic, sid) {
  const N = parseInt(sid.slice(-2), 10);
  const d = parseInt(sid.slice(-1), 10);
  return { N, d, text: topic.param(N, d) };
}
